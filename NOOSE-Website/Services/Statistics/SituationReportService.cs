using System.Globalization;
using System.Security.Claims;
using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.EntityFrameworkCore;
using NOOSE_Website.Authorization;
using NOOSE_Website.Data;
using NOOSE_Website.Data.Entities.Common;
using NOOSE_Website.Models.Enums;
using NOOSE_Website.Models.Statistics;

namespace NOOSE_Website.Services.Statistics;

/// <inheritdoc cref="ISituationReportService" />
public class SituationReportService(
    IDbContextFactory<AppDbContext> dbFactory,
    IStatisticsService statistics,
    IFinancingStatisticsService financingStatistics,
    INotificationService notifications,
    ILogger<SituationReportService> logger) : ISituationReportService
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    };

    private static readonly CultureInfo DeDe = CultureInfo.GetCultureInfo("de-DE");

    public async Task<bool> GenerateDueAsync(DateTime nowUtc, CancellationToken cancellationToken = default)
    {
        var previousMonth = new DateTime(nowUtc.Year, nowUtc.Month, 1, 0, 0, 0, DateTimeKind.Utc).AddMonths(-1);
        var monthEnd = previousMonth.AddMonths(1);

        // A row generated by hand BEFORE its own month was over covers only part of it, and "the existence of the
        // report is the marker" then permanently pre-empted the complete month-end run the panel promises. Such a
        // row is treated as provisional and replaced; a row written after the month closed still blocks, which is
        // what makes the worker idempotent.
        await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);
        // created WITHIN its own reporting month, not merely "before the end": an unstamped or legacy CreatedAt
        // then reads as unknown rather than as provisional, and unknown must not trigger a replacement
        var provisional = await db.SituationReports
            .AsNoTracking()
            .Where(l => l.Year == previousMonth.Year && l.Month == previousMonth.Month)
            .AllAsync(l => l.CreatedAt >= previousMonth && l.CreatedAt < monthEnd, cancellationToken);
        var any = await db.SituationReports
            .AnyAsync(l => l.Year == previousMonth.Year && l.Month == previousMonth.Month, cancellationToken);

        var bulletin = await GenerateMonthAsync(previousMonth.Year, previousMonth.Month,
            replaceExisting: any && provisional, triggerId: null, cancellationToken);
        return bulletin is not null;
    }

    public async Task<SituationReport?> GenerateMonthAsync(int year, int month, bool replaceExisting, string? triggerId,
        CancellationToken cancellationToken = default)
    {
        await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);

        var existing = await db.SituationReports
            .Where(l => l.Year == year && l.Month == month)
            .ToListAsync(cancellationToken);
        if (existing.Count > 0)
        {
            if (!replaceExisting)
            {
                return null;
            }
            foreach (var alt in existing)
            {
                alt.IsDeleted = true;
                alt.DeletedAt = DateTime.UtcNow;
                alt.DeletedById = triggerId;
            }
        }

        var report = await statistics.GetReportAsync(isLeadership: true, meId: null, cancellationToken: cancellationToken);
        // classified records left out
        var released = await statistics.GetReportAsync(isLeadership: false, meId: null, cancellationToken: cancellationToken);
        var financing = await financingStatistics.GetMonthAsync(year, month, cancellationToken);
        var title = $"Lagebericht {new DateTime(year, month, 1).ToString("MMMM yyyy", DeDe)}";

        var bulletin = new SituationReport
        {
            Year = year,
            Month = month,
            Title = title,
            SnapshotJson = JsonSerializer.Serialize(report, JsonOptions),
            // own column: SnapshotJson is a frozen wire format that must not gain members
            FinancingJson = JsonSerializer.Serialize(financing, JsonOptions),
            ReleasedSnapshotJson = JsonSerializer.Serialize(released, JsonOptions),
            CreatedById = triggerId,
        };
        db.SituationReports.Add(bulletin);
        await db.SaveChangesAsync(cancellationToken);

        await NotifyLeadershipAsync(db, bulletin, title, triggerId, cancellationToken);
        return bulletin;
    }

    public Task<List<SituationReportHead>> GetArchiveAsync(CancellationToken cancellationToken = default)
        => ArchiveAsync(releasedOnly: false, cancellationToken);

    private async Task<List<SituationReportHead>> ArchiveAsync(bool releasedOnly, CancellationToken cancellationToken)
    {
        await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);

        var rows = await db.SituationReports
            .Where(l => !releasedOnly || l.ReleasedSnapshotJson != null)
            .OrderByDescending(l => l.Year).ThenByDescending(l => l.Month).ThenByDescending(l => l.CreatedAt)
            .Select(l => new { l.Id, l.Year, l.Month, l.Title, l.CreatedAt, l.CreatedById })
            .ToListAsync(cancellationToken);

        var creatorIds = rows.Where(r => !string.IsNullOrEmpty(r.CreatedById))
            .Select(r => r.CreatedById!).Distinct().ToList();
        var names = creatorIds.Count == 0
            ? new Dictionary<string, string>()
            : await db.Users.Where(u => creatorIds.Contains(u.Id))
                .Select(u => new { u.Id, u.Codename }).ToDictionaryAsync(u => u.Id, u => u.Codename, cancellationToken);

        return rows.Select(r => new SituationReportHead(r.Id, r.Year, r.Month, r.Title, r.CreatedAt,
            string.IsNullOrEmpty(r.CreatedById) ? null : names.GetValueOrDefault(r.CreatedById))).ToList();
    }

    public Task<SituationReportDisplay?> GetDisplayAsync(string id, CancellationToken cancellationToken = default)
        => DisplayAsync(id, released: false, cancellationToken);

    /// <summary>A report from the full snapshot or, for partners, the one without classified records (null when absent).</summary>
    private async Task<SituationReportDisplay?> DisplayAsync(string id, bool released, CancellationToken cancellationToken)
    {
        await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);
        var bulletin = await db.SituationReports.FirstOrDefaultAsync(l => l.Id == id, cancellationToken);
        var json = released ? bulletin?.ReleasedSnapshotJson : bulletin?.SnapshotJson;
        if (bulletin is null || string.IsNullOrWhiteSpace(json))
        {
            return null;
        }

        StatisticsReport? report;
        try
        {
            report = JsonSerializer.Deserialize<StatisticsReport>(json, JsonOptions);
        }
        catch (JsonException ex)
        {
            logger.LogWarning(ex, "Lagebericht {Id} hat einen unlesbaren Snapshot.", id);
            return null;
        }
        if (report is null)
        {
            return null;
        }

        // reports archived before funding requests existed carry no value here; degrade instead of failing
        FinancingReport? financing = null;
        if (!string.IsNullOrWhiteSpace(bulletin.FinancingJson))
        {
            try
            {
                financing = JsonSerializer.Deserialize<FinancingReport>(bulletin.FinancingJson, JsonOptions);
            }
            catch (JsonException ex)
            {
                logger.LogWarning(ex, "Lagebericht {Id} hat unlesbare Finanzierungszahlen.", id);
            }
        }

        string? generatedBy = null;
        if (!string.IsNullOrEmpty(bulletin.CreatedById))
        {
            generatedBy = await db.Users.Where(u => u.Id == bulletin.CreatedById)
                .Select(u => u.Codename).FirstOrDefaultAsync(cancellationToken);
        }

        return new SituationReportDisplay(bulletin.Id, bulletin.Title, bulletin.CreatedAt, generatedBy, report, financing);
    }

    public async Task<List<SituationReportHead>> GetArchiveForAsync(ClaimsPrincipal viewer, CancellationToken cancellationToken = default)
    {
        await RequireReadAsync(viewer, cancellationToken);
        if (!viewer.IsPartner())
        {
            return await GetArchiveAsync(cancellationToken);
        }
        // released snapshots only
        var heads = await ArchiveAsync(releasedOnly: true, cancellationToken);
        return heads.Select(h => h with { GeneratedBy = null }).ToList();
    }

    public async Task<SituationReportDisplay?> GetDisplayForAsync(string id, ClaimsPrincipal viewer, CancellationToken cancellationToken = default)
    {
        await RequireReadAsync(viewer, cancellationToken);
        if (viewer.GetPartnerAgency() is not { } agency)
        {
            return await GetDisplayAsync(id, cancellationToken);
        }
        var display = await DisplayAsync(id, released: true, cancellationToken);
        if (display is null)
        {
            return null;
        }
        await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);
        var factionIds = (display.Report.TopFactions ?? []).Select(e => SituationReportRedaction.LastSegment(e.Href)).ToList();
        var visible = (await db.Factions.Where(f => factionIds.Contains(f.Id))
            .OnlyPartnerVisible(db, agency, viewer.GetAgentId())
            .Select(f => f.Id)
            .ToListAsync(cancellationToken)).ToHashSet();
        return display with
        {
            Report = SituationReportRedaction.ForPartner(display.Report, visible),
            Financing = null,
            GeneratedBy = null,
        };
    }

    /// <summary>Leadership and supervision read every report; a partner only with the agency's reports function.</summary>
    private async Task RequireReadAsync(ClaimsPrincipal viewer, CancellationToken cancellationToken)
    {
        if (viewer.IsPartner())
        {
            await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);
            Permission.RequireInternalOrPartnerFeature(viewer,
                await PartnerVisibility.FeaturesAsync(db, viewer.GetPartnerAgency(), cancellationToken), PartnerFeature.SituationReports);
            return;
        }
        if (!viewer.IsLeadership() && !viewer.IsOnlyReader())
        {
            throw new UnauthorizedAccessException("Lageberichte sind der Führung vorbehalten.");
        }
    }

    public async Task DeleteAsync(string id, ClaimsPrincipal actor, CancellationToken cancellationToken = default)
    {
        Permission.RequireLeadership(actor);
        await using var db = await dbFactory.CreateDbContextAsync(cancellationToken);
        var bulletin = await db.SituationReports.FirstOrDefaultAsync(l => l.Id == id, cancellationToken);
        if (bulletin is null)
        {
            return;
        }
        bulletin.IsDeleted = true;
        bulletin.DeletedAt = DateTime.UtcNow;
        bulletin.DeletedById = actor.GetAgentId();
        await db.SaveChangesAsync(cancellationToken);
    }

    private async Task NotifyLeadershipAsync(AppDbContext db, SituationReport bulletin, string title,
        string? triggerId, CancellationToken cancellationToken)
    {
        try
        {
            var leadershipIds = await db.Users.OnlySelectable()
                .Where(u => u.Rank != null && u.Rank >= Rank.SupervisorySpecialAgent)
                .Select(u => u.Id)
                .ToListAsync(cancellationToken);

            await notifications.NotifyManyAsync(leadershipIds, NotificationType.SituationReport,
                $"Neuer {title}", $"/lageberichte/{bulletin.Id}", triggerId, cancellationToken);
        }
        catch (Exception ex)
        {
            logger.LogWarning(ex, "Benachrichtigung über den neuen Lagebericht {Id} fehlgeschlagen.", bulletin.Id);
        }
    }
}
